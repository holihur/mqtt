package parser

import "testing"

func FuzzSplitFrame(f *testing.F) {
	f.Add([]byte{0x10, 0x0e, 0x00, 0x04, 0x4d, 0x51, 0x54, 0x54, 0x04, 0x02, 0x00, 0x3c, 0x00, 0x03, 0x61, 0x62, 0x63})
	f.Add([]byte{0x30, 0x07, 0x00, 0x03, 0x61, 0x2f, 0x62, 0x68, 0x69})
	f.Fuzz(func(t *testing.T, data []byte) {
		_, _, _ = SplitFrame(data, 1<<20)
		_, _, _ = SplitFrame(data, 1024)
		if len(data) > 0 {
			_, _, _ = DecodeVarInt(data)
			_, _, _ = DecodeVarInt(data[1:])
		}
	})
}
